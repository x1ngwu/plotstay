"""Prepare the reference font for browsers without a local WenQuanYi install.

Run with fonttools==4.66.1 and brotli==1.2.0 installed in a temporary venv.
Assets are committed; this is not part of the app build or runtime.
Outlines and embedded bitmap strikes are preserved. Unicode subsets keep a
new visitor from downloading the entire collection before reading a page.
"""
from pathlib import Path
import logging
import sys
from fontTools import subset
from fontTools.ttLib import TTFont

logging.getLogger("fontTools.subset").setLevel(logging.ERROR)
root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc")
target = root / "apps/web/public/themes/lime/fonts"
original = TTFont(source, fontNumber=2)
available = set(original.getBestCmap())
original.close()
texts = [path.read_text() for path in (root / "apps/web/src").rglob("*")
         if path.suffix in (".ts", ".astro")]
texts += [(root / path).read_text() for path in ("scripts/seed.ts", "scripts/seed-discovery.ts", "scripts/discovery-copy.ts")]
common = (set(range(0x250)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040))
          | set(map(ord, "".join(texts)))) & available
groups = {"core": common}
for code in sorted(available - common):
    groups.setdefault(f"u{code // 512:03x}", set()).add(code)

def unicode_ranges(codes):
    ranges = []
    start = end = None
    for code in sorted(codes):
        if end is not None and code == end + 1:
            end = code
        else:
            if start is not None:
                ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
            start = end = code
    if start is not None:
        ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return ",".join(ranges)

css = ["/* Generated by scripts/prepare-lime-font.py. Same Sharp face as digi-tech-lime. */"]
for name, codes in groups.items():
    font = TTFont(source, fontNumber=2, recalcTimestamp=False)
    options = subset.Options()
    options.drop_tables = [tag for tag in options.drop_tables if tag not in ("EBDT", "EBLC", "EBSC")]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=codes)
    worker.subset(font)
    font.flavor = "woff2"
    filename = f"zen-hei-sharp-{name}.woff2"
    font.save(target / filename)
    font.close()
    css.append("@font-face {\n  font-family: 'PlotStay Zen Hei Sharp';\n"
               "  src: local('WenQuanYi Zen Hei Sharp'), "
               f"url('/themes/lime/fonts/{filename}') format('woff2');\n"
               "  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n"
               f"  unicode-range: {unicode_ranges(codes)};\n}}")
(root / "packages/themes/lime-fonts.css").write_text("\n".join(css) + "\n")
print({"subsets": len(groups), "core_glyphs": len(common),
       "core_bytes": (target / "zen-hei-sharp-core.woff2").stat().st_size,
       "all_codepoints": len(available)})
