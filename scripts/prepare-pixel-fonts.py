"""Build lossless web-delivery subsets of the two user-provided Dinkie faces.

Use the same temporary fonttools / brotli environment as prepare-lime-font.py.
Original files and notices stay intact; C&C and Press Start are never modified.
The generated assets are checked in, so Python is not a build/runtime dependency.
All characters exposed by the original CSS remain available via unicode-range.
"""
from pathlib import Path
from hashlib import sha256
import json
import logging
from fontTools import subset
from fontTools.ttLib import TTFont

logging.getLogger('fontTools.subset').setLevel(logging.ERROR)
root = Path(__file__).resolve().parents[1]
source_dir = root / 'apps/web/public/font-preview/fonts'
target_dir = root / 'apps/web/src/assets/fonts/pixel'
target_dir.mkdir(parents=True, exist_ok=True)
text_paths = list((root / 'apps/web/src').rglob('*.astro')) + list((root / 'apps/web/src').rglob('*.ts'))
text_paths += [root / 'scripts' / name for name in ['seed.ts', 'seed-discovery.ts', 'discovery-copy.ts']]
common = set(map(ord, ''.join(path.read_text() for path in text_paths)))
ranges = [(0x2010, 0x2027), (0x3000, 0x303F), (0x3400, 0x4DBF),
          (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0xFF00, 0xFFEF),
          (0x20000, 0x2A6DF), (0x2F800, 0x2FA1F)]

def unicode_ranges(codes):
    groups = []
    for code in sorted(codes):
        if groups and code == groups[-1][1] + 1:
            groups[-1][1] = code
        else:
            groups.append([code, code])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in groups)

css = ['/* Generated by scripts/prepare-pixel-fonts.py; do not edit by hand. */']
report = []
for pixels in [7, 9]:
    source = source_dir / f'DinkieBitmap-{pixels}px.woff2'
    original = TTFont(source)
    source_cmap = original.getBestCmap()
    available = {code for code in source_cmap if any(a <= code <= b for a, b in ranges)}
    punctuation = available & set(range(0x2010, 0x2028))
    core = (available & common) - punctuation
    groups = {'punctuation': punctuation, 'core': core}
    for code in sorted(available - core - punctuation):
        groups.setdefault(f'u{code // 512:03x}', set()).add(code)
    seen = set()
    files = []
    for group, codes in groups.items():
        if not codes:
            continue
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.drop_tables = [tag for tag in options.drop_tables if tag not in ('EBDT', 'EBLC', 'EBSC')]
        options.name_IDs = ['*']
        options.name_languages = ['*']
        options.name_legacy = True
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=codes)
        worker.subset(font)
        name = f'dinkie-{pixels}-{group}.woff2'
        font.flavor = 'woff2'
        font.save(target_dir / name)
        font.close()
        check = TTFont(target_dir / name)
        cmap = check.getBestCmap()
        assert set(cmap) == codes, name
        assert not (seen & codes), name
        seen |= codes
        assert check['head'].unitsPerEm == original['head'].unitsPerEm
        for key in ['ascent', 'descent', 'lineGap']:
            assert getattr(check['hhea'], key) == getattr(original['hhea'], key), (name, key)
        for code, glyph in cmap.items():
            old_glyph = source_cmap[code]
            assert check['hmtx'][glyph] == original['hmtx'][old_glyph], (name, code, 'metrics')
            assert check['glyf'][glyph].getCoordinates(check['glyf']) == original['glyf'][old_glyph].getCoordinates(original['glyf']), (name, code, 'outlines')
        check.close()
        css.append("@font-face {\n"
                   f"  font-family: 'Preview Dinkie {pixels}';\n"
                   f"  src: url('../../apps/web/src/assets/fonts/pixel/{name}') format('woff2');\n"
                   "  font-style: normal; font-weight: 400; font-display: swap;\n"
                   f"  unicode-range: {unicode_ranges(codes)};\n}}")
        files.append({'file': name, 'glyphs': len(codes), 'bytes': (target_dir / name).stat().st_size})
    assert seen == available
    original.close()
    report.append({'source': source.name, 'sourceSha256': sha256(source.read_bytes()).hexdigest(),
                   'exposedCodepoints': len(available), 'files': files})
    print({'face': pixels, 'files': len(files), 'coreBytes': (target_dir / f'dinkie-{pixels}-core.woff2').stat().st_size, 'allGlyphsVerified': len(seen)}, flush=True)

# The pixel fonts miss a few UI symbols. Preserve the exact existing fallback
# glyphs, without making an arrow download the legacy font's large CJK core.
source = root / 'apps/web/public/themes/lime/fonts/zen-hei-sharp-core.woff2'
original = TTFont(source)
source_cmap = original.getBestCmap()
dinkie9 = TTFont(source_dir / 'DinkieBitmap-9px.woff2')
dinkie_codes = set(dinkie9.getBestCmap())
dinkie9.close()
codes = {code for code in source_cmap if code < 0x3000 or code not in dinkie_codes}
font = TTFont(source, recalcTimestamp=False)
options = subset.Options()
options.drop_tables = [tag for tag in options.drop_tables if tag not in ('EBDT', 'EBLC', 'EBSC')]
options.name_IDs = ['*']
options.name_languages = ['*']
options.name_legacy = True
worker = subset.Subsetter(options=options)
worker.populate(unicodes=codes)
worker.subset(font)
name = 'pixel-fallback.woff2'
font.flavor = 'woff2'
font.save(target_dir / name)
font.close()
check = TTFont(target_dir / name)
assert set(check.getBestCmap()) == codes
assert check['head'].unitsPerEm == original['head'].unitsPerEm
for key in ['ascent', 'descent', 'lineGap']:
    assert getattr(check['hhea'], key) == getattr(original['hhea'], key)
for code, glyph in check.getBestCmap().items():
    old_glyph = source_cmap[code]
    assert check['hmtx'][glyph] == original['hmtx'][old_glyph]
    assert check['glyf'][glyph].getCoordinates(check['glyf']) == original['glyf'][old_glyph].getCoordinates(original['glyf'])
check.close()
original.close()
css.append("@font-face {\n  font-family: 'PlotStay Pixel Fallback';\n"
           f"  src: url('../../apps/web/src/assets/fonts/pixel/{name}') format('woff2');\n"
           "  font-style: normal; font-weight: 400; font-display: swap;\n"
           f"  unicode-range: {unicode_ranges(codes)};\n}}")
report.append({'source': str(source.relative_to(root)), 'sourceSha256': sha256(source.read_bytes()).hexdigest(),
               'exposedCodepoints': len(codes), 'files': [{'file': name, 'glyphs': len(codes), 'bytes': (target_dir / name).stat().st_size}]})
print({'fallbackBytes': (target_dir / name).stat().st_size, 'allGlyphsVerified': len(codes)}, flush=True)
(root / 'packages/themes/pixel-fonts.css').write_text('\n'.join(css) + '\n')
(target_dir / 'manifest.json').write_text(json.dumps(report, indent=2) + '\n')
